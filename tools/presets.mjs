// dubstep, riddim, tribe, deep/dub et halftime. Seules les valeurs qui diffèrent
// des défauts sont écrites ; les chargeurs complètent avec les défauts.
// Les choix (tables, formes…) sont écrits par leur nom, pas par index.

const mods = (...slots) => {
  const o = {};
  slots.forEach(([src, dst, amt], k) => {
    o[`mod${k + 1}.src`] = src;
    o[`mod${k + 1}.dst`] = dst;
    o[`mod${k + 1}.amt`] = amt;
  });
  return o;
};

